function schema(native: DatabaseSync) {
  return native.prepare("SELECT type,name,tbl_name AS tableName,sql FROM sqlite_schema WHERE sql IS NOT NULL AND name NOT GLOB 'sqlite_*' ORDER BY type,name").all();
}
function cells(native: DatabaseSync, objects = PORTABLE_RUNTIME_SCHEMA_STATEMENTS) {
  return Object.fromEntries(objects.filter(object => object.type === "table").map(object => {
    const quoted = '"' + object.name.replaceAll('"', '""') + '"', withRowid = !/WITHOUT\s+ROWID/i.test(object.sql);
    const statement = native.prepare(`SELECT ${withRowid ? 'rowid AS "__hidden_rowid",' : ""}* FROM ${quoted}`);
    statement.setReadBigInts(true);
    const result = statement.all().map(row => Object.fromEntries(Object.entries(row).map(([key, value]) => [key,
      value === null ? { type: "null" } : typeof value === "bigint" ? { type: "integer", value: value.toString() }
        : typeof value === "number" ? { type: "real", value } : value instanceof Uint8Array ? { type: "blob", value: Buffer.from(value).toString("hex") }
          : { type: "text", value }]))).sort((a, b) => JSON.stringify(a).localeCompare(JSON.stringify(b)));
    return [object.name, result];
  }));
}
